import type { Browser, Page, PuppeteerNode } from "puppeteer-core";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

const HTML_FRAGMENT = Symbol("document-html");
export type DocumentHtml = { readonly [HTML_FRAGMENT]: true; readonly value: string };

/** HTML text / quoted-attribute encoding, never a URL or CSS allowlist. */
export function escapeDocumentText(value: unknown): string {
  return String(value ?? "").replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[character]!);
}

/** Only literal markup and nested fragments generated by this tag are trusted. */
export function documentHtml(strings: TemplateStringsArray, ...values: unknown[]): DocumentHtml {
  let value = strings[0];
  values.forEach((item, index) => {
    value += isDocumentHtml(item) ? item.value : escapeDocumentText(item);
    value += strings[index + 1];
  });
  return Object.freeze({ [HTML_FRAGMENT]: true as const, value });
}

function isDocumentHtml(value: unknown): value is DocumentHtml {
  return typeof value === "object" && value !== null && HTML_FRAGMENT in value;
}

export function joinDocumentHtml(fragments: DocumentHtml[]): DocumentHtml {
  return Object.freeze({ [HTML_FRAGMENT]: true as const, value: fragments.map((part) => part.value).join("") });
}

export const DOCUMENT_RENDER_LIMITS = Object.freeze({
  maxHtmlBytes: 1_048_576,
  maxPdfBytes: 10_485_760,
  launchMs: 10_000,
  operationMs: 10_000,
  cleanupMs: 2_000,
  maxConcurrentRenders: 2,
});

export function withDocumentTimeout<T>(operation: Promise<T>, milliseconds: number, label: string): Promise<T> {
  let timer: ReturnType<typeof setTimeout>;
  const deadline = new Promise<never>((_, reject) => {
    timer = setTimeout(() => reject(new Error(`Document ${label} timed out`)), milliseconds);
  });
  return Promise.race([operation, deadline]).finally(() => clearTimeout(timer));
}

const CSP = "default-src 'none'; script-src 'none'; connect-src 'none'; img-src 'none'; font-src 'none'; media-src 'none'; object-src 'none'; frame-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'";
let activeRenders = 0;

/** Finite local renderer; no navigation or storage access. Every request is denied. */
export async function renderDocumentPdf(
  html: DocumentHtml,
  renderer: Pick<PuppeteerNode, "launch">,
  executablePath: string,
): Promise<Buffer> {
  if (!isDocumentHtml(html) || Buffer.byteLength(html.value, "utf8") > DOCUMENT_RENDER_LIMITS.maxHtmlBytes) {
    throw new Error("Document HTML exceeds the local rendering limit");
  }
  if (activeRenders >= DOCUMENT_RENDER_LIMITS.maxConcurrentRenders) throw new Error("Document renderer is busy; retry later");
  activeRenders++;
  let profile: string | undefined;
  let browser: Browser | undefined;
  let page: Page | undefined;
  const bounded = <T>(operation: Promise<T>, label: string) =>
    withDocumentTimeout(operation, DOCUMENT_RENDER_LIMITS.operationMs, label);
  try {
    profile = await mkdtemp(join(tmpdir(), "circulair-document-"));
    browser = await renderer.launch({
      executablePath,
      headless: true,
      userDataDir: profile,
      timeout: DOCUMENT_RENDER_LIMITS.launchMs,
      protocolTimeout: DOCUMENT_RENDER_LIMITS.operationMs,
      // Do not bypass the process sandbox. Unsupported hosts must fail closed.
      args: ["--disable-dev-shm-usage", "--disable-gpu", "--disable-software-rasterizer",
        "--disable-background-networking", "--disable-component-update", "--no-first-run"],
    });
    page = await bounded(browser.newPage(), "page creation");
    page.setDefaultTimeout(DOCUMENT_RENDER_LIMITS.operationMs);
    page.setDefaultNavigationTimeout(DOCUMENT_RENDER_LIMITS.operationMs);
    await bounded(page.setJavaScriptEnabled(false), "script restriction");
    await bounded(page.setBypassServiceWorker(true), "service-worker restriction");
    await bounded(page.setRequestInterception(true), "request restriction");
    page.on("request", (request) => {
      // No URL inspection, allowlist fallthrough, or network probe. This also denies file/data URLs.
      void request.abort("blockedbyclient").catch(() => undefined);
    });
    const content = html.value.replace(/<head>/i, `<head><meta http-equiv="Content-Security-Policy" content="${CSP}">`);
    await bounded(page.setContent(content, { waitUntil: "domcontentloaded", timeout: DOCUMENT_RENDER_LIMITS.operationMs }), "HTML rendering");
    const pdf = await bounded(page.pdf({
      format: "A4", printBackground: true, timeout: DOCUMENT_RENDER_LIMITS.operationMs,
      margin: { top: "20mm", right: "15mm", bottom: "20mm", left: "15mm" },
    }), "PDF rendering");
    const result = Buffer.from(pdf);
    if (result.length > DOCUMENT_RENDER_LIMITS.maxPdfBytes || !result.subarray(0, 5).equals(Buffer.from("%PDF-"))) {
      throw new Error("Document renderer returned invalid or oversized PDF output");
    }
    return result;
  } finally {
    try {
      if (page) await withDocumentTimeout(page.close(), DOCUMENT_RENDER_LIMITS.cleanupMs, "page cleanup").catch(() => undefined);
      if (browser) {
        try {
          await withDocumentTimeout(browser.close(), DOCUMENT_RENDER_LIMITS.cleanupMs, "browser cleanup");
        } catch {
          const process = browser.process();
          if (!process || !process.kill("SIGKILL")) throw new Error("Document browser cleanup failed");
        }
      }
    } finally {
      // No PDF output is written to disk; remove only the temporary profile owned by this operation.
      try {
        if (profile) await rm(profile, { recursive: true, force: true, maxRetries: 2, retryDelay: 50 });
      } finally {
        activeRenders--;
      }
    }
  }
}

export interface DocumentActor { id: number; }
export interface DocumentAccessRecord {
  uploadedById: number | null;
  accessLevel: string;
  expiresAt?: Date | string | null;
  fileUrl?: string | null;
  fileKey?: string | null;
}

/** Conservative owner-only metadata policy until verified organization membership exists. */
export function canReadDocumentMetadata(actor: DocumentActor, document: DocumentAccessRecord, now = new Date()): boolean {
  if (!Number.isSafeInteger(actor.id) || actor.id <= 0 || document.uploadedById !== actor.id) return false;
  if (document.expiresAt != null) {
    const expiry = new Date(document.expiresAt).getTime();
    if (!Number.isFinite(expiry) || expiry <= now.getTime()) return false;
  }
  return ["public", "organization", "private", "government"].includes(document.accessLevel);
}

/** Signing alone does not make a public object private. No verified private bucket exists here. */
export async function rejectUnverifiedPrivateDocumentDownload(): Promise<never> {
  throw new Error("Private document downloads are unavailable until storage privacy and per-document authorization are verified");
}

/** Reused by proposed central guards; invoked before any DB, rendering, or storage operation. */
export function assertDocumentPublishingAvailable(): never {
  throw new Error("Document publishing is disabled pending private storage and resource authorization verification");
}

export function documentMetadataOnly<T extends DocumentAccessRecord>(actor: DocumentActor, rows: T[], now = new Date()) {
  return rows.filter((row) => canReadDocumentMetadata(actor, row, now)).map((row) => {
    const { fileUrl: _url, fileKey: _key, ...metadata } = row;
    return { ...metadata, fileUrl: null, fileKey: null };
  });
}

export function canonicalDocumentReportType(type: string): string {
  return ({ epr_compliance: "compliance_report", battery_cert: "battery_certificate" } as Record<string, string>)[type] ?? type;
}
